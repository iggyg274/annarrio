#!/usr/bin/env python3
"""Import the sprite sheets this game uses from ../elthenassets.

Reads ../elthenassets/assets/catalog.json (generated by that repo's pipeline), copies
the referenced PNGs into ./assets/elthen/ and writes ./js/asset_data.js, a plain script
that defines `window.ASSET_DATA` (works from file:// without a server).

Only labelled data is taken from the catalog. Two sheets are still `draft` there
(elthen.ratfolk_axe, elthen.akaname: animations named row0..rowN); for those this
script applies the game's own labels (OVERRIDES below), decided by looking at the frames.
The asset repository itself is never modified.

Usage:  python3 tools/import_assets.py [path/to/elthenassets]
"""
import json
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "elthenassets"

USED = [
    "elthen.adventurer", "elthen.dwarf",                      # player classes (dwarf also a monster)
    "elthen.bat", "elthen.frog", "elthen.pig", "elthen.ratfolk_axe", "elthen.akaname",
    "elthen.octopus", "elthen.imp", "elthen.witch",            # monsters
    "elthen.dungeon", "elthen.arena",                          # tilesets
    "elthen.dungeon_collectables",                             # items
    "elthen.torch", "elthen.banner", "elthen.shadows",         # decoration
    "elthen.hex", "elthen.green_portal", "elthen.purple_portal",  # effects
]

# Game-side labels for sheets that are still drafts in the asset catalog.
OVERRIDES = {
    "elthen.ratfolk_axe": {
        "name": "Ratfolk Axeman", "kind": "monster", "facing": "right",
        "tags": ["ratfolk", "melee", "hostile", "dungeon"],
        "anchor": {"x": 27, "y": 31},
        "rename": {"row0": "idle", "row1": "run", "row2": "attack", "row3": "hurt", "row4": "die"},
        "timing": {"idle": (0.15, "LOOP"), "run": (0.09, "LOOP"), "attack": (0.06, "NORMAL"),
                   "hurt": (0.1, "NORMAL"), "die": (0.12, "NORMAL")},
    },
    "elthen.akaname": {
        "name": "Akaname", "kind": "monster", "facing": "right",
        "tags": ["yokai", "melee", "hostile", "reach"],
        "anchor": {"x": 16, "y": 31},
        "rename": {"row0": "idle", "row1": "run", "row2": "attack", "row3": "die"},
        "timing": {"idle": (0.14, "LOOP"), "run": (0.09, "LOOP"), "attack": (0.07, "NORMAL"),
                   "die": (0.12, "NORMAL")},
    },
}

KEEP_TILE_FIELDS = ("id", "col", "row", "role", "solid", "weight", "tags", "name", "corners")


def fill_tiles(sheet, png_path):
    """Per terrain: the plain fill tiles usable for random floors.

    Candidates come from the catalog (all four corners = terrain, weight > 0). A few
    catalog entries are mislabelled (e.g. brick wall tiles inside the pit_room stamp are
    tagged as stone floor), so each candidate is also compared with the terrain's sample
    tile and dropped when it looks clearly different. Done here because browsers forbid
    reading pixels of images loaded from file:// URLs.
    """
    try:
        from PIL import Image, ImageChops, ImageStat
    except ImportError:  # no Pillow: trust the catalog
        Image = None
    fw = sheet["frameWidth"]
    cols = sheet["width"] // fw
    img = Image.open(png_path).convert("RGB") if Image else None

    def tile(i):
        x, y = (i % cols) * fw, (i // cols) * fw
        return img.crop((x, y, x + fw, y + fw))

    out = {}
    for name, ter in sheet.get("terrains", {}).items():
        ids = [t["id"] for t in sheet["tiles"]
               if t.get("corners") == [name] * 4 and t.get("weight", 1) > 0]
        if img is not None:
            ref = tile(ter["sampleTile"])
            ref_std = ImageStat.Stat(ref.convert("L")).stddev[0]
            keep = []
            for i in ids:
                diff = sum(ImageStat.Stat(ImageChops.difference(tile(i), ref)).mean) / 3
                std = ImageStat.Stat(tile(i).convert("L")).stddev[0]
                # same colour and same amount of texture as the sample (no patch edges)
                # (only enforced for flat-coloured terrains: sand's speckle varies by design)
                if diff < 8 and (ref_std > 5 or abs(std - ref_std) < 1.5):
                    keep.append(i)
            ids = keep or [ter["sampleTile"]]
        out[name] = ids
    return out


def slim_sheet(s):
    out = {k: s[k] for k in ("id", "name", "kind", "tags", "frameWidth", "frameHeight",
                             "width", "height", "facing", "anchor", "hitbox", "description")
           if k in s}
    out["image"] = "assets/elthen/" + Path(s["image"]).name
    if s.get("animations"):
        out["animations"] = {n: {"frames": a["frames"], "frameDuration": a["frameDuration"],
                                 "playMode": a.get("playMode", "LOOP")}
                             for n, a in s["animations"].items()}
    if s.get("regions"):
        out["regions"] = s["regions"]
    if s.get("terrains"):
        out["terrains"] = s["terrains"]
    if s.get("stamps"):
        out["stamps"] = {n: {k: v for k, v in st.items()
                             if k in ("col", "row", "cols", "rows", "mask", "tags", "layer")}
                         for n, st in s["stamps"].items()}
    if s.get("tiles"):
        out["tiles"] = [{k: t[k] for k in KEEP_TILE_FIELDS if k in t} for t in s["tiles"]]
    ov = OVERRIDES.get(s["id"])
    if ov:
        for k in ("name", "kind", "facing", "tags", "anchor"):
            out[k] = ov[k]
        anims = {}
        for old, new in ov["rename"].items():
            a = dict(out["animations"][old])
            a["frameDuration"], a["playMode"] = ov["timing"][new]
            anims[new] = a
        out["animations"] = anims
        out["labelledBy"] = "game (draft in asset catalog)"
    return out


def pit_tiles(sheet, png_path):
    """Split the 'pit' fill tiles into `top` (a full-width stone lip along the top edge, for
    pit cells whose northern neighbour is floor) and `inner` (uniform darkness)."""
    from PIL import Image
    fw = sheet["frameWidth"]
    cols = sheet["width"] // fw
    img = Image.open(png_path).convert("RGB")
    ref = img.getpixel(((sheet["terrains"]["pit"]["sampleTile"] % cols) * fw + fw // 2,
                        (sheet["terrains"]["pit"]["sampleTile"] // cols) * fw + fw // 2))
    top, inner = [], []
    candidates = [t["id"] for t in sheet["tiles"] if t.get("corners") == ["pit"] * 4 and t.get("weight", 1) > 0]
    for i in candidates:
        x0, y0 = (i % cols) * fw, (i // cols) * fw
        rows, lit_rows = [], []
        for y in range(fw):
            px = [img.getpixel((x0 + x, y0 + y)) for x in range(fw)]
            isdark = [sum(abs(a - b) for a, b in zip(p, ref)) < 30 for p in px]
            rows.append(all(isdark))
            lit_rows.append(not any(isdark))
        if all(rows):
            inner.append(i)
        else:
            lip = rows.index(True) if True in rows else fw
            if 2 <= lip <= 6 and all(rows[lip:]) and all(lit_rows[:lip]):
                top.append(i)
    return {"top": top, "inner": inner}


def void_color(sheet, png_path):
    """Colour of the solid-rock 'void' drawn above wall caps (top-left pixel of the wall frame stamp)."""
    try:
        from PIL import Image
    except ImportError:
        return "#2f2f2e"
    stamps = sheet.get("stamps", {})
    st = stamps.get("wall_frame") or stamps.get("enclosure")
    if not st:
        return "#2f2f2e"
    fw = sheet["frameWidth"]
    r, g, b, *_ = Image.open(png_path).convert("RGBA").getpixel((st["col"] * fw, st["row"] * fw))
    return "#%02x%02x%02x" % (r, g, b)


def main():
    cat_path = SRC / "assets" / "catalog.json"
    catalog = json.loads(cat_path.read_text())
    by_id = {s["id"]: s for s in catalog["assets"]}
    missing = [i for i in USED if i not in by_id]
    if missing:
        sys.exit(f"missing assets in catalog: {missing}")

    dest = HERE / "assets" / "elthen"
    dest.mkdir(parents=True, exist_ok=True)
    sheets = {}
    for aid in USED:
        s = by_id[aid]
        shutil.copyfile(SRC / "assets" / s["image"], dest / Path(s["image"]).name)
        sheets[aid] = slim_sheet(s)
        if s.get("terrains"):
            sheets[aid]["fillTiles"] = fill_tiles(s, SRC / "assets" / s["image"])
            sheets[aid]["voidColor"] = void_color(s, SRC / "assets" / s["image"])
            if "pit" in s["terrains"]:
                sheets[aid]["pitTiles"] = pit_tiles(s, SRC / "assets" / s["image"])

    data = {"source": str(cat_path), "schemaVersion": catalog.get("schemaVersion"),
            "pack": catalog.get("packs"), "sheets": sheets}
    js = ("// GENERATED by tools/import_assets.py from the elthenassets catalog. Do not edit.\n"
          "window.ASSET_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    (HERE / "js" / "asset_data.js").write_text(js)
    print(f"imported {len(sheets)} sheets -> assets/elthen/, js/asset_data.js ({len(js)//1024} KiB)")


if __name__ == "__main__":
    main()
